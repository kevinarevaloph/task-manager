-- Public Marketing Content Calendar setup / migration
-- Run this in Supabase Dashboard > SQL Editor.
-- WARNING: Anyone with access to this site's public Supabase configuration can
-- read, add, edit, and delete all rows in public.marketing_content.

create table if not exists public.marketing_content (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) <= 180),
  content_type text not null default 'other'
    check (content_type in ('social','blog','email','website','campaign','video','design','other')),
  channel text,
  status text not null default 'idea'
    check (status in ('idea','draft','in-review','approved','scheduled','published','on-hold')),
  publish_date date not null,
  publish_time time,
  campaign text,
  content_url text,
  brief text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- If the earlier private/authenticated schema was already installed, remove
-- its owner-only policies and NOT NULL owner column so anonymous inserts work.
drop policy if exists "Users can read their own marketing content" on public.marketing_content;
drop policy if exists "Users can create their own marketing content" on public.marketing_content;
drop policy if exists "Users can update their own marketing content" on public.marketing_content;
drop policy if exists "Users can delete their own marketing content" on public.marketing_content;
alter table public.marketing_content drop column if exists created_by;

create index if not exists marketing_content_publish_date_idx
  on public.marketing_content (publish_date);

alter table public.marketing_content enable row level security;

drop policy if exists "Public can read marketing content" on public.marketing_content;
create policy "Public can read marketing content"
  on public.marketing_content for select to anon, authenticated
  using (true);

drop policy if exists "Public can create marketing content" on public.marketing_content;
create policy "Public can create marketing content"
  on public.marketing_content for insert to anon, authenticated
  with check (true);

drop policy if exists "Public can update marketing content" on public.marketing_content;
create policy "Public can update marketing content"
  on public.marketing_content for update to anon, authenticated
  using (true)
  with check (true);

drop policy if exists "Public can delete marketing content" on public.marketing_content;
create policy "Public can delete marketing content"
  on public.marketing_content for delete to anon, authenticated
  using (true);

grant select, insert, update, delete on public.marketing_content to anon, authenticated;
grant usage, select on sequence public.marketing_content_id_seq to anon, authenticated;
